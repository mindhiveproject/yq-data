"""Regenerate the golden-value fixtures.

Usage:

    python -m venv .venv && source .venv/bin/activate
    pip install -r tests/unit/golden/requirements.txt
    python tests/unit/golden/generate.py

Writes ``fixtures/_inputs.json`` (the signals) and one fixture per method
family -- see the table in README.md. Commit them all.

To rebuild one group only (``filter``, ``spectral``, ``stats``, ``cardiac``,
``rppg``, ``rms``) -- which also needs only that group's libraries -- name it:

    python tests/unit/golden/generate.py filter
 The exact library
versions used are recorded inside each fixture under ``generatedBy``.
"""

import sys
import warnings
from pathlib import Path

import numpy as np

from inputs import build_signals
from ref_common import as_float32, dump, versions

import ref_filter

FIXTURES = Path(__file__).parent / "fixtures"


def rms(x):
    return float(np.sqrt(np.mean(np.square(np.asarray(x, np.float64)))))


def dbfs(value, floor=-100.0):
    """dBFS relative to 1.0 -- matches src/analyzer/methods/stats.ts `dbfs`."""
    if value <= 0.0:
        return floor
    return float(max(floor, 20.0 * np.log10(value)))


def build_rms(signals):
    cases = []
    for name, sig in signals.items():
        f64 = [np.asarray(c, np.float64) for c in sig["channels"]]
        f32 = [as_float32(c) for c in sig["channels"]]
        cases.append(
            {
                "signal": name,
                # Reference for the pure `rms()` primitive (float64 in, float64 out).
                "expected": [rms(c) for c in f64],
                # Reference for RMSAnalyzer, whose input is float32 and whose
                # output is a Float32Array.
                "expectedFromFloat32": [rms(c) for c in f32],
                "expectedDbfs": [dbfs(rms(c)) for c in f32],
                # AES17 dBFS: a full-scale *sine* reads 0 dBFS, i.e. the RMS is
                # referenced to 1/sqrt(2) rather than 1.0 (+3.01 dB).
                "expectedDbfsAes17": [dbfs(rms(c) * np.sqrt(2.0)) for c in f32],
            }
        )
    return {
        "reference": (
            "numpy: sqrt(mean(x**2)); dBFS = 20*log10(rms) relative to 1.0, floor -100; "
            "AES17 dBFS = 20*log10(rms*sqrt(2))"
        ),
        "cases": cases,
    }


def write(name, doc):
    dump(FIXTURES / f"{name}.json", {"generatedBy": versions(), **doc})


def groups(signals):
    """Fixture name -> (group, builder). Heavy imports happen inside the builders."""

    def lazy(module, fn, *args):
        def build():
            return getattr(__import__(module), fn)(*args)

        return build

    return {
        "rms": ("rms", lambda: build_rms(signals)),
        "stats": ("stats", lazy("ref_stats", "build_stats", signals)),
        "window": ("stats", lazy("ref_stats", "build_windows")),
        "spectrum": ("spectral", lazy("ref_spectral", "build_spectrum", signals)),
        "band_power": ("spectral", lazy("ref_spectral", "build_band_power", signals)),
        "filter_design": ("filter", ref_filter.build_design),
        "lfilter": ("filter", lambda: ref_filter.build_lfilter(signals)),
        "filter_streaming": ("filter", lambda: ref_filter.build_streaming(signals)),
        "filtfilt": ("filter", lambda: ref_filter.build_filtfilt(signals)),
        "filter_butter": ("filter", ref_filter.build_butter),
        "filter_fir": ("filter", ref_filter.build_fir),
        "window_functions": ("filter", ref_filter.build_window_functions),
        "filter_extras": ("filter", lambda: ref_filter.build_filtering_extras(signals)),
        "cardiac": ("cardiac", lazy("ref_cardiac", "build_cardiac", signals)),
        "rppg": ("rppg", lazy("ref_rppg", "build_rppg", signals)),
    }


def main(only):
    warnings.filterwarnings("ignore")  # neurokit2/yasa deprecation chatter
    signals = build_signals()
    FIXTURES.mkdir(exist_ok=True)

    if not only:
        dump(
            FIXTURES / "_inputs.json",
            {
                "generatedBy": versions(),
                "comment": "Generated by generate.py from inputs.py. Do not hand-edit.",
                "signals": {
                    name: {
                        "description": sig["description"],
                        "fs": sig["fs"],
                        "channels": [
                            np.asarray(c, np.float64).tolist() for c in sig["channels"]
                        ],
                        **({"truth": sig["truth"]} if "truth" in sig else {}),
                    }
                    for name, sig in signals.items()
                },
            },
        )

    chosen = {
        name: build
        for name, (group, build) in groups(signals).items()
        if not only or group in only
    }
    for name, build in chosen.items():
        write(name, build())

    print(f"wrote {len(chosen)} fixtures" + ("" if only else f" and {len(signals)} signals"))
    print("versions:", versions())
    return 0


if __name__ == "__main__":
    sys.exit(main(set(sys.argv[1:])))
